"""Generate URI-to-model bindings from the reviewed Mihomo field manifest.

No source checkout or network is needed. --check verifies the committed output.
"""

import argparse
import hashlib
import json
import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
PROTOCOLS = ("ss", "vmess", "vless", "trojan", "hysteria2", "tuic", "wireguard", "anytls")
PLUGINS = ("obfs", "v2ray-plugin", "gost-plugin", "shadow-tls", "restls", "jls", "kcptun")


def generate():
    manifest = json.loads((ROOT / "docs/unified_node_fields.json").read_text(encoding="utf-8"))
    header = (ROOT / "src/unified_node.hpp").read_text(encoding="utf-8")
    structs = {}
    for name, body in re.findall(r"struct (\w+) \{(.*?)\n\};", header, re.S):
        fields = {}
        for line in body.splitlines():
            match = re.match(r"\s+(.+?)\s+(\w+)\{.*\};", line)
            if match and not match[1].startswith("static "):
                fields[match[2]] = match[1]
        structs[name] = fields

    def expression(path):
        parts = path.split(".")
        if parts.pop(0) != "configuration" or "[]" in path:
            return None
        current_type = "node_configuration"
        result = "configuration"
        guards = []
        for index, part in enumerate(parts):
            match = re.fullmatch(r"(\w+)(?:<(\w+)>)?", part)
            if not match or match[1] not in structs.get(current_type, {}):
                return None
            field, alternative = match.groups()
            current_type = structs[current_type][field]
            result += "." + field
            if alternative:
                guards.append(f"std::holds_alternative<node_model::{alternative}>({result})")
                result = f"std::get<node_model::{alternative}>({result})"
                current_type = alternative
            if index != len(parts) - 1 and current_type.startswith("std::optional<"):
                current_type = current_type[len("std::optional<"):-1]
                result = f"present({result})"
        base_type = current_type
        if base_type.startswith("std::optional<"):
            base_type = base_type[len("std::optional<"):-1]
        if base_type in structs or base_type in ("shadowsocks_plugin", "transport_payload"):
            return None
        return result, guards

    # Keep small functions for each adapter/transport: fewer irrelevant branches
    # at runtime, and bounded work for intraprocedural static analysis.
    bindings = {context: {} for context in
                ["proxy-" + item for item in PROTOCOLS] + ["plugin-" + item for item in PLUGINS]}
    supported_rows = []
    contexts = ["proxy-" + item for item in PROTOCOLS] + ["plugin-" + item for item in PLUGINS]
    for row in manifest["rows"]:
        if row["context"] not in contexts or row["disposition"] != "mapped":
            continue
        decoded = expression(row["model_path"])
        if decoded is None:
            continue
        target, guards = decoded
        key = row["kernel_path"].removeprefix("proxies[].")
        if key in ("plugin", "network"):
            continue
        # select_detail has already established the protocol variant. Transport
        # and plugin alternatives still need guards before accessing their fields.
        guards = [guard for guard in guards
                  if not guard.endswith("(configuration.detail)")]
        bindings[row["context"]].setdefault(tuple(guards), []).append((key, target))
        supported_rows.append({"context": row["context"], "kernel_path": row["kernel_path"],
                               "model_path": row["model_path"]})

    lines = ["// Generated by tools/generate_node_input_bindings.py; do not edit.",
             "// Kernel revision: " + manifest["kernel_revision"],
             "// Each protocol consumes only its audited fields and active transport/plugin.",
             "// The repository requires anonymous namespaces for implementation details.",
             "// NOLINTBEGIN(llvm-prefer-static-over-anonymous-namespace)"]
    chunk_size = 12
    for context, groups in bindings.items():
        name = "bind_" + context.replace("-", "_")
        dispatch = []
        for group_index, (guards, fields) in enumerate(groups.items()):
            calls = []
            for offset in range(0, len(fields), chunk_size):
                helper = f"{name}_group_{group_index}_part_{offset // chunk_size}"
                lines += [f"auto {helper}(options& source, node_configuration& configuration) -> void {{"]
                for key, target in fields[offset:offset + chunk_size]:
                    reader = "read_pem" if key.rsplit('.', 1)[-1] in ("certificate", "private-key") else "read_value"
                    lines += [f'    if (const auto* value = find_option(source, "{key}")) {{',
                              f"        {reader}(*value, {target});", "    }"]
                lines += ["}", ""]
                calls.append(f"{helper}(source, configuration);")
            if guards:
                dispatch += ["    if (" + " && ".join(guards) + ") {"]
                dispatch += ["        " + call for call in calls]
                dispatch.append("    }")
            else:
                dispatch += ["    " + call for call in calls]
        lines += [f"auto {name}(options& source, node_configuration& configuration) -> void {{"]
        lines += dispatch + ["}", ""]

    lines += ["auto bind_kernel_fields(options& source, node_configuration& configuration,",
              "                        uri_protocol protocol) -> void {", "    switch (protocol) {"]
    for protocol in PROTOCOLS:
        lines += [f"    case uri_protocol::{manifest['protocols'][protocol]}:",
                  f"        bind_proxy_{protocol}(source, configuration);"]
        if protocol == "ss":
            lines += [f"        bind_plugin_{plugin.replace('-', '_')}(source, configuration);"
                      for plugin in PLUGINS]
        lines.append("        break;")
    lines += ["    case uri_protocol::unspecified:", "        fail(parse_error::unsupported_protocol);",
              "    }", "}", "// NOLINTEND(llvm-prefer-static-over-anonymous-namespace)", ""]
    coverage = {"kernel_revision": manifest["kernel_revision"],
                "bound_leaf_rows": supported_rows,
                "note": "URI aliases and specialized credential/transport validation live in node_input.cpp. "
                        "Container and discriminant rows are handled by URI assembly; this lists generated leaf bindings."}
    formatted = subprocess.run(
        ["clang-format", "--assume-filename=" + str(ROOT / "src/node_input_bindings.inc")],
        input="\n".join(lines), text=True, encoding="utf-8", capture_output=True, check=True,
    ).stdout
    return formatted, json.dumps(coverage, ensure_ascii=False, indent=2) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    digest = hashlib.sha256((ROOT / "third_party/nlohmann/json.hpp").read_bytes()).hexdigest()
    if digest != "aaf127c04cb31c406e5b04a63f1ae89369fccde6d8fa7cdda1ed4f32dfc5de63":
        raise SystemExit("Vendored nlohmann/json v3.12.0 header checksum mismatch")
    yaml_root = ROOT / "third_party/rapidyaml"
    provenance = json.loads((yaml_root / "PROVENANCE.json").read_text(encoding="utf-8"))
    for name, expected in provenance["sha256"].items():
        if hashlib.sha256((yaml_root / name).read_bytes()).hexdigest() != expected:
            raise SystemExit(f"Vendored RapidYAML checksum mismatch: {name}")
    if args.check:
        for path in sorted((ROOT / "src").glob("node_input_*.inc")):
            if path.name == "node_input_bindings.inc":
                continue
            subprocess.run(["clang-format", "--dry-run", "--Werror", str(path)], check=True)
    source, coverage = generate()
    outputs = ((ROOT / "src/node_input_bindings.inc", source),
               (ROOT / "docs/node_input_fields.json", coverage))
    for path, text in outputs:
        if args.check:
            if path.read_text(encoding="utf-8") != text:
                raise SystemExit(f"Stale generated file: {path}")
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
    print("Node input bindings match the reviewed model field manifest.")


if __name__ == "__main__":
    main()
