"""Generate complete private C++20 cache reflection; --check detects model drift."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parent.parent


def inventory():
    model = (ROOT / 'src/unified_node.hpp').read_text(encoding='utf-8')
    records = {}
    enums = {}
    for filename, namespace, selected in [
        ('unified_node.hpp', 'node_model', None),
        ('subscription_account.hpp', 'subscription_data', {'account_metadata'}),
        ('profile_storage.hpp', 'profile_storage', {'profile_settings', 'profile_record'}),
    ]:
        text = (ROOT / 'src' / filename).read_text(encoding='utf-8')
        for name, body in re.findall(r'^struct (\w+) \{(.*?)^\};', text, re.S | re.M):
            if selected is not None and name not in selected:
                continue
            fields = []
            for line in body.splitlines():
                match = re.match(r'\s+(.+?)\s+(\w+)\{.*?\};', line)
                if match and not match[1].startswith('static '):
                    fields.append((match[2], match[1]))
                elif line.strip() and not line.lstrip().startswith(('//', 'static ')):
                    raise ValueError(f'Unrecognized member syntax in {namespace}::{name}: {line.strip()}')
            records[namespace + '::' + name] = fields
    for name, body in re.findall(r'enum class (\w+)\s*:[^{]+\{(.*?)\};', model, re.S):
        enums['node_model::' + name] = [entry.strip() for entry in body.split(',') if entry.strip()]
    variants = {}
    for name, body in re.findall(r'using (\w+)\s*=\s*std::variant<(.*?)>;', model, re.S):
        variants['node_model::' + name] = [item.strip() for item in body.replace('\n', ' ').split(',')]
    assert len(enums) == 3 and len(variants) == 5
    return records, enums, variants


def generate():
    records, enums, variants = inventory()
    model_records = {k: v for k, v in records.items() if k.startswith('node_model::')}
    schema = {'records': model_records, 'enums': enums, 'variants': variants}
    digest = hashlib.sha256(json.dumps(schema, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    lines = ['// Generated by tools/generate_profile_codec.py; do not edit.',
             '// Every non-static model field participates, including all variant alternatives.',
             f'inline constexpr std::string_view model_schema{{"{digest}"}};', '']
    names = sorted({field for fields in records.values() for field, _ in fields} |
                   {'version', 'model_schema', 'nodes', 'type', 'value', 'ticks', 'period_num', 'period_den'})
    lines += ['inline constexpr auto cache_field_names = std::to_array<std::string_view>({']
    lines += [f'    "{name}",' for name in names]
    lines += ['});', '']
    for name, fields in records.items():
        lines += [f'template <> struct record_traits<{name}> {{',
                  f'    static constexpr std::string_view name{{"{name.split("::")[-1]}"}};',
                  '    static constexpr auto members = std::make_tuple(']
        lines += [f'        std::pair{{std::string_view{{"{field}"}}, &{name}::{field}}},' for field, _ in fields]
        if fields:
            lines[-1] = lines[-1].removesuffix(',')
        lines += ['    );', '};', '']
    for name, values in enums.items():
        lines += [f'template <> struct enum_traits<{name}> {{',
                  f'    static constexpr auto values = std::to_array<std::pair<std::string_view, {name}>>({{']
        lines += [f'        {{"{value}", {name}::{value}}},' for value in values]
        lines += ['    });', '};', '']
    # Name tags make a reorder of variant alternatives harmless to the wire format.
    for name in sorted({alt for alternatives in variants.values() for alt in alternatives}):
        qualified = name if name.startswith('std::') else 'node_model::' + name
        tag = name.replace('std::', '').replace('chrono::', '')
        lines += [f'template <> struct variant_tag<{qualified}> {{',
                  f'    static constexpr std::string_view name{{"{tag}"}};', '};', '']
    output = subprocess.run(['clang-format', '--assume-filename=' + str(ROOT / 'src/profile_codec_fields.inc')],
                            input='\n'.join(lines), text=True, encoding='utf-8', capture_output=True, check=True).stdout
    manifest = {'model_schema': digest, 'model_record_count': len(model_records),
                'model_field_count': sum(len(fields) for fields in model_records.values()),
                'records': records, 'enums': enums, 'variants': variants}
    return output, json.dumps(manifest, ensure_ascii=False, indent=2) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source, manifest = generate()
    for path, text in [(ROOT / 'src/profile_codec_fields.inc', source),
                       (ROOT / 'docs/profile_cache_fields.json', manifest)]:
        if args.check:
            if path.read_text(encoding='utf-8') != text:
                raise SystemExit(f'Stale profile cache reflection: {path}')
        else:
            path.write_text(text, encoding='utf-8', newline='\n')
    print('Profile cache reflection covers every model field and variant.')


if __name__ == '__main__':
    main()
