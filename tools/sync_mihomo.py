"""One entry point for pinned Mihomo extraction, code generation and verification."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys
from urllib.request import Request, urlopen

from mihomo.extract import ROOT, OUTPUT, extract, json_text, read_json, write_outputs

LOCK = ROOT / "tools/mihomo/upstream.lock.json"
REPOSITORY = "https://github.com/MetaCubeX/mihomo.git"


def verify_vendors():
    directory = ROOT / "third_party/nlohmann"
    provenance = (directory / "PROVENANCE.txt").read_text(encoding="utf-8")
    expected = re.search(r"json.hpp SHA-256: ([0-9a-f]{64})", provenance)
    if expected is None or hashlib.sha256((directory / "json.hpp").read_bytes()).hexdigest() != expected[1]:
        raise ValueError("Vendored nlohmann/json header checksum mismatch")
    directory = ROOT / "third_party/rapidyaml"
    for name, expected in read_json(directory / "PROVENANCE.json")["sha256"].items():
        if hashlib.sha256((directory / name).read_bytes()).hexdigest() != expected:
            raise ValueError(f"Vendored RapidYAML checksum mismatch: {name}")


def git(*arguments):
    return subprocess.check_output(["git", *map(str, arguments)], text=True, encoding="utf-8").strip()


def resolve_release():
    request = Request("https://api.github.com/repos/MetaCubeX/mihomo/releases/latest",
                      headers={"Accept": "application/vnd.github+json", "User-Agent": "BlankQuick-source-sync"})
    with urlopen(request, timeout=30) as response:
        release = json.load(response)
    tag = release["tag_name"]
    if release["draft"] or release["prerelease"] or not re.fullmatch(r"v\d+\.\d+\.\d+", tag):
        raise ValueError(f"Expected a stable Mihomo release, received {tag}")
    references = dict((reference, digest) for digest, reference in (
        line.split() for line in git("ls-remote", REPOSITORY, "refs/tags/" + tag,
                                     "refs/tags/" + tag + "^{}").splitlines()))
    revision = references.get("refs/tags/" + tag + "^{}", references.get("refs/tags/" + tag, ""))
    if not re.fullmatch(r"[0-9a-f]{40}", revision):
        raise ValueError("Invalid upstream tag revision")
    return {"repository": REPOSITORY, "tag": tag, "commit": revision,
            "release_url": release["html_url"]}


def checkout(lock, supplied, allow_download):
    source = supplied or ROOT / "out/upstream" / ("mihomo-" + lock["tag"])
    if not source.exists():
        if not allow_download:
            raise ValueError("No upstream checkout. Run python tools/sync_mihomo.py sync first.")
        source.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(["git", "clone", "--depth", "1", "--branch", lock["tag"], REPOSITORY, str(source)], check=True)
    if git("-C", source, "rev-parse", "HEAD") != lock["commit"]:
        raise ValueError(f"Mihomo source revision differs from lock: {source}")
    if git("-C", source, "status", "--porcelain", "--untracked-files=all"):
        raise ValueError(f"Mihomo source checkout is dirty: {source}")
    return source


def contract_outputs(lock):
    policy = read_json(ROOT / "tools/mihomo/model_mapping.json")
    directory = ROOT / "src/domain/nodes/include/blank/nodes"
    revision = ('// Generated by tools/sync_mihomo.py; do not edit.\n'
                f'inline constexpr std::string_view kernel_revision{{"{lock["commit"]}"}};\n'
                f'inline constexpr std::string_view kernel_version{{"{lock["tag"][1:]}"}};\n')
    names = ["// Generated by tools/sync_mihomo.py; do not edit."]
    for protocol, model in policy["protocols"].items():
        names += [f"case protocol_type::{model}:", f'    return "{protocol}";']
    names = subprocess.run(["clang-format", "--assume-filename=" + str(directory / "kernel_protocol_names.inc")],
                           input="\n".join(names) + "\n", text=True, encoding="utf-8", capture_output=True, check=True).stdout
    return {directory / "kernel_revision.inc": revision,
            directory / "kernel_protocol_names.inc": names}


def generate(facts):
    from mihomo import bindings, cache, coverage, exporter
    # Render everything before publishing; a mapping error must not half-update C++.
    outputs = {}
    for module in (bindings, cache, exporter, coverage):
        outputs.update(module.outputs(facts))
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("sync", "generate", "check"))
    parser.add_argument("--source", type=Path, help="Existing clean checkout of the locked commit")
    parser.add_argument("--latest", action="store_true", help="Resolve GitHub's latest stable release (sync only)")
    parser.add_argument("--offline", action="store_true", help="Verify committed source snapshots without network or checkout")
    args = parser.parse_args()
    if args.latest and args.action != "sync":
        parser.error("--latest is only valid with sync")
    if args.source and args.action == "generate":
        parser.error("generate uses committed snapshots; use sync/check with --source")
    if args.offline and (args.action != "check" or args.source or args.latest):
        parser.error("--offline is only valid with check and no source/latest option")
    verify_vendors()
    lock = resolve_release() if args.latest else read_json(LOCK)
    check = args.action == "check"
    if args.action != "generate" and not args.offline:
        source = checkout(lock, args.source, args.action == "sync")
        facts = extract(source, lock["commit"])
    else:
        facts = {name: read_json(OUTPUT / name) for name in (
            "unified_node_fields.json", "runtime_config_schema.json", "source-provenance.json",
            "config-fields.json", "raw-defaults.json")}
    manifest = facts["unified_node_fields.json"]
    if manifest["kernel_revision"] != lock["commit"]:
        raise ValueError("Source snapshots and release lock differ; run sync")
    provenance = facts["source-provenance.json"]
    if provenance["mapping_sha256"] != hashlib.sha256((ROOT / "tools/mihomo/model_mapping.json").read_bytes()).hexdigest():
        raise ValueError("Client mappings changed; run sync against source")
    outputs = {OUTPUT / name: json_text(value) for name, value in facts.items()}
    outputs.update(contract_outputs(lock))
    outputs.update(generate(facts))
    # Publish only after all source reconciliation and rendering have succeeded.
    write_outputs(outputs, check)
    if args.action == "sync":
        write_outputs({LOCK: json_text(lock)}, False)
    print(f'Mihomo {lock["tag"]} ({lock["commit"][:12]}): source facts and all generated contracts verified.')


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError, subprocess.CalledProcessError) as error:
        print(f"Mihomo sync failed: {error}", file=sys.stderr)
        raise SystemExit(1) from error
