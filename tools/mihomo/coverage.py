"""Compile every semantic model mapping, including inactive variant alternatives."""

import re

from .extract import ROOT


def outputs(facts):
    manifest = facts["unified_node_fields.json"]
    code = ['// Generated by tools/sync_mihomo.py; do not edit.',
            '#include <blank/nodes/unified_node.hpp>', '#include <type_traits>',
            '#include <utility>', '#include <variant>', '', 'namespace {',
            'template <typename Value>', '    requires std::is_class_v<Value>',
            '[[nodiscard]] constexpr decltype(auto) unwrap(const Value& value) noexcept {',
            '    if constexpr (requires { *value; }) { return *value; }',
            '    else { return (value); }', '}', '']
    for protocol, model in manifest['protocols'].items():
        code += [f'static_assert(node_model::{model}_param::protocol_tag == node_model::protocol_type::{model});',
                 f'static_assert(node_model::kernel_protocol_name(node_model::protocol_type::{model}) == "{protocol}");']
    expressions = set()
    for row in manifest['rows']:
        if row['disposition'] != 'mapped':
            continue
        path = row['model_path'].removesuffix('.active_alternative')
        expression = 'std::declval<const node_model::unified_node&>()'
        for part in path.split('.'):
            match = re.fullmatch(r'(\w+)(?:<(\w+)>)?(\[\])?', part)
            if match is None:
                raise ValueError(f'Unrecognized C++ model path: {path}')
            member, alternative, sequence = match.groups()
            expression = f'unwrap({expression}).{member}'
            if alternative:
                expression = f'std::get<node_model::{alternative}>({expression})'
            if sequence:
                expression = f'unwrap({expression}).front()'
        expressions.add(expression)
    for expression in sorted(expressions):
        code.append(f'static_assert(requires {{ {expression}; }});')
    code += ['}', '']
    import subprocess
    output = subprocess.run(['clang-format', '--assume-filename=' + str(ROOT / 'generated/mihomo/model_contract.cpp')],
                            input='\n'.join(code), text=True, encoding='utf-8', capture_output=True, check=True).stdout
    return {ROOT / 'generated/mihomo/model_contract.cpp': output}
