"""Generate Mihomo exporters from the audited, protocol-specific model mapping."""

import collections
import json
import itertools
import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[2]


def generate(manifest):
    model = (ROOT / 'src/domain/nodes/include/blank/nodes/unified_node.hpp').read_text(encoding='utf-8')
    records = {}
    for name, body in re.findall(r'struct (\w+) \{(.*?)\n\};', model, re.S):
        records[name] = {}
        for line in body.splitlines():
            match = re.match(r'\s+(.+?)\s+(\w+)\{.*\};', line)
            if match and not match[1].startswith('static '):
                records[name][match[2]] = match[1]

    def unwrap(kind):
        for wrapper in ('std::optional<', 'std::unique_ptr<'):
            if kind.startswith(wrapper):
                return kind[len(wrapper):-1].removeprefix('const '), True
        return kind, False

    def resolve(path, prefix, owner, unwrap_last=False):
        assert path.startswith(prefix + '.'), (prefix, path)
        parts = path[len(prefix) + 1:].split('.')
        expression = 'source'
        guards = []
        kind = owner
        terminal_optional = False
        for index, part in enumerate(parts):
            if part == 'active_alternative':
                assert index == len(parts) - 1
                return f'variant_name({expression})', guards, 'std::string_view', False
            match = re.fullmatch(r'(\w+)(?:<(\w+)>)?', part)
            assert match and match[1] in records.get(kind, {}), (kind, part, path)
            field, alternative = match.groups()
            expression += '.' + field
            kind = records[kind][field]
            kind_base, optional = unwrap(kind)
            if optional and (index != len(parts) - 1 or unwrap_last or alternative):
                guards.append(f'{expression} != std::nullopt' if kind.startswith('std::optional<')
                              else f'{expression} != nullptr')
                expression = (f'{expression}.value()' if kind.startswith('std::optional<')
                              else f'(*{expression})')
                kind = kind_base
                terminal_optional = index == len(parts) - 1
            if alternative:
                guards.append(f'std::holds_alternative<node_model::{alternative}>({expression})')
                expression = f'std::get<node_model::{alternative}>({expression})'
                kind = alternative
        return expression, guards, kind, terminal_optional

    contexts = collections.OrderedDict()
    for row in manifest['rows']:
        if row['disposition'] != 'mapped':
            continue
        tree = contexts.setdefault(row['context'], {})
        for part in row['kernel_path'].removeprefix('proxies[].').split('.'):
            name = part.removesuffix('[]')
            tree = tree.setdefault(name, {'children': {}, 'row': None, 'array': False})
            tree['array'] |= part.endswith('[]')
            node = tree
            tree = tree['children']
        # Aliases with identical kernel paths must not silently replace one another.
        assert node['row'] is None or node['row']['model_path'] == row['model_path'], row
        node['row'] = row

    lines = [
        '// Generated by tools/sync_mihomo.py; do not edit.',
        '// Kernel revision: ' + manifest['kernel_revision'],
        '// JSON object properties intentionally use insertion subscripts; standard default arguments are allowed.',
        '// NOLINTBEGIN(llvm-prefer-static-over-anonymous-namespace,fuchsia-default-arguments-calls,cppcoreguidelines-pro-bounds-avoid-unchecked-container-access)',
    ]
    covered = []
    manual = []

    def helper(context, children, prefix, owner, path):
        name = 'export_' + re.sub(r'[^a-z0-9_]', '_', context + '_' + path)
        operations = []
        for key, entry in children.items():
            row = entry['row']
            assert row is not None, (context, path, key)
            model_path = row['model_path']
            required = row['required_by_decoder']
            if model_path.endswith('.core.protocol'):
                manual.append(row)
                continue
            # These containers are selected by their discriminant; the corresponding
            # plugin/Snell contexts below contain their audited concrete fields.
            if model_path.endswith(('.plugin', '.obfs_opts')) and not entry['children']:
                manual.append(row)
                continue
            expression, guards, kind, presence = resolve(
                model_path, prefix, owner, bool(entry['children']))
            if entry['children']:
                if entry['array']:
                    assert kind.startswith('std::vector<'), (key, kind)
                    element = kind[len('std::vector<'):-1]
                    nested = helper(context, entry['children'], model_path + '[]', element,
                                    path + '_' + key)
                    statement = f'emit_array(result, "{key}", {expression}, {nested}, {str(required or presence).lower()});'
                else:
                    assert kind in records, (context, key, kind)
                    nested = helper(context, entry['children'], model_path, kind, path + '_' + key)
                    if presence:
                        expression, guards, _, _ = resolve(model_path, prefix, owner, False)
                        statement = f'emit_optional_object(result, "{key}", {expression}, {nested});'
                    else:
                        statement = f'emit_object(result, "{key}", {nested}({expression}), {str(required).lower()});'
            else:
                base_kind, _ = unwrap(kind)
                assert base_kind not in records, (context, model_path, base_kind)
                unsigned = row['kernel_type'].lstrip('*').startswith(('uint', '[]uint'))
                statement = (f'write_field(result, "{key}", {expression}, {str(required).lower()}, '
                             f'{str(unsigned).lower()});')
            operations.append((guards, statement))
            if not row.get('synthetic'):
                covered.append(row)
        blocks = []
        for guards, grouped in itertools.groupby(operations, key=lambda item: item[0]):
            statements = [item[1] for item in grouped]
            if guards:
                blocks.append(['    if (' + ' && '.join(guards) + ') {'] +
                              ['        ' + statement for statement in statements] + ['    }'])
            else:
                blocks.append(['    ' + statement for statement in statements])
        parts = []
        # Keep generated presence/variant checks in small, auditable functions.
        if len(blocks) > 4:
            for index in range(0, len(blocks), 4):
                part = name + '_part_' + str(index // 4)
                parts.append(part)
                lines.append(f'auto {part}(json& result, const node_model::{owner}& source) -> void {{')
                for block in blocks[index:index + 4]:
                    lines.extend(block)
                lines.extend(['}', ''])
        lines.extend([f'auto {name}(const node_model::{owner}& source) -> json {{',
                      '    auto result = json::object();'])
        if parts:
            lines.extend(f'    {part}(result, source);' for part in parts)
        else:
            for block in blocks:
                lines.extend(block)
        lines.extend(['    return result;', '}', ''])
        return name

    roots = {}
    # A synthetic root makes all model paths relative to unified_node.
    for context, tree in contexts.items():
        def fill_parents(entry):
            paths = []
            for child in entry['children'].values():
                paths.extend(fill_parents(child))
            if entry['row'] is None:
                parts = [path.split('.')[:-1] for path in paths]
                common = []
                for values in zip(*parts):
                    if len(set(values)) != 1:
                        break
                    common.append(values[0])
                assert common, (context, paths)
                entry['row'] = {'model_path': '.'.join(common), 'required_by_decoder': False,
                                'kernel_type': 'object', 'synthetic': True}
            return [entry['row']['model_path']]
        for entry in tree.values():
            fill_parents(entry)
        for entry in tree.values():
            def root_paths(current):
                if current['row']:
                    current['row'] = dict(current['row'], model_path='node.' + current['row']['model_path'])
                for child in current['children'].values():
                    root_paths(child)
            root_paths(entry)
        roots[context] = helper(context, tree, 'node', 'unified_node', 'root')

    lines.extend(['auto export_node_fields(const node_model::unified_node& source) -> json {',
                  '    auto result = json::object();', '    switch (source.core.protocol) {'])
    for protocol, tag in manifest['protocols'].items():
        lines.extend([f'    case node_model::protocol_type::{tag}:',
                      f'        result = {roots["proxy-" + protocol]}(source);',
                      f'        result["type"] = "{protocol}";'])
        if protocol == 'ss':
            for context in roots:
                if context.startswith('plugin-'):
                    lines.append(f'        merge_export(result, {roots[context]}(source));')
        if protocol == 'snell':
            for context in roots:
                if context.startswith('snell-obfs-'):
                    lines.append(f'        merge_export(result, {roots[context]}(source));')
        lines.append('        break;')
    lines.extend(['    case node_model::protocol_type::unspecified:',
                  '        fail(configuration_error::invalid_node);', '    }',
                  '    return result;', '}',
                  '// NOLINTEND(llvm-prefer-static-over-anonymous-namespace,fuchsia-default-arguments-calls,cppcoreguidelines-pro-bounds-avoid-unchecked-container-access)', ''])
    # model paths were qualified only to generate expressions, not to change the manifest.
    output = subprocess.run(['clang-format', '--assume-filename=' + str(ROOT / 'src/domain/runtime_config/mihomo_export_fields.inc')],
                            input='\n'.join(lines), text=True, encoding='utf-8',
                            capture_output=True, check=True).stdout
    assert len(covered) + len(manual) == sum(row['disposition'] == 'mapped' for row in manifest['rows'])
    coverage = {'kernel_revision': manifest['kernel_revision'], 'protocols': manifest['protocols'],
                'mapped_rows': len(covered) + len(manual), 'generated_rows': len(covered),
                'discriminant_container_rows': len(manual),
                'note': 'Every mapped row is generated or explicitly handled as a protocol/plugin discriminant or container. Excluded rows are never emitted.'}
    return output, json.dumps(coverage, ensure_ascii=False, indent=2) + '\n'


def outputs(facts):
    source, coverage = generate(facts['unified_node_fields.json'])
    schema = facts['runtime_config_schema.json']
    if schema['kernel_revision'] != json.loads(coverage)['kernel_revision']:
        raise ValueError('Runtime schema and model use different kernel revisions')
    schema_lines = ['// Generated by tools/sync_mihomo.py; do not edit.',
                    'constexpr auto input_schema = std::to_array<schema_field>({']
    schema_lines += ['    {.path = "' + f['path'] + '", .type = "' + f['go_type'] + '"},' for f in schema['fields']]
    schema_lines += ['});', '']
    schema_source = subprocess.run(['clang-format', '--assume-filename=' + str(ROOT / 'src/domain/runtime_config/runtime_schema.inc')],
                                   input='\n'.join(schema_lines), text=True, encoding='utf-8',
                                   capture_output=True, check=True).stdout
    return {ROOT / 'src/domain/runtime_config/mihomo_export_fields.inc': source,
            ROOT / 'generated/mihomo/mihomo_export_fields.json': coverage,
            ROOT / 'src/domain/runtime_config/runtime_schema.inc': schema_source}
